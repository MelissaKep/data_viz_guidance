def main():
    """Run the complete data retrieval, mapping, and export workflow."""
    print_section(
        "U.S. CENSUS PROPORTIONAL SYMBOL MAP — 1920 VS. 2020"
    )
    print(
        "This example compares state population counts across a century.\n"
        "It retrieves official Census data and 2020 TIGER/Line boundaries.\n"
        "No Census API key is required for the historical table source."
    )

    try:
        population = get_historical_population()
        boundaries = get_state_boundaries()
        mapped = prepare_map_data(population, boundaries)
        figure = create_map(mapped)
        interactive_figure = create_interactive_map(mapped)
        export_outputs(mapped, figure, interactive_figure)

        print_section("SUCCESS — ALL OUTPUTS WERE CREATED")
        print(f"Output folder: {OUTPUT_FOLDER}")
        print(
            "Displaying the interactive Plotly map first. Hover over any "
            "state symbol to inspect both population counts."
        )

        # Explicitly render Plotly in the active notebook/browser output.
        # The standalone HTML file is also saved for opening outside Jupyter.
        interactive_figure.show()

        print("Displaying the high-resolution static reference-style map.")
        plt.show()

    except Exception as exc:
        print_section("THE SCRIPT COULD NOT COMPLETE")
        print(f"Error: {exc}")
        print("\nFull diagnostic traceback:")
        traceback.print_exc()
        print(
            "\nIf the Census webpage table layout has changed, check the "
            "official source URL and the table-extraction section."
        )


if __name__ == "__main__":
    main()