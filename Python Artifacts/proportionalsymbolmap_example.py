def get_state_boundaries():
    """Download and load official 2020 TIGER/Line state boundaries."""
    print_section("STEP 2 — LOADING 2020 TIGER/LINE STATE BOUNDARIES")

    zip_path = OUTPUT_FOLDER / "tl_2020_us_state.zip"
    download_file(TIGER_URL, zip_path, "2020 TIGER/Line state boundaries")

    # GeoPandas can read a zipped shapefile directly.
    boundaries = gpd.read_file(f"zip://{zip_path}")

    required = {"NAME", "GEOID", "geometry"}
    missing = required.difference(boundaries.columns)
    if missing:
        raise ValueError(f"TIGER/Line file is missing columns: {sorted(missing)}")

    print(f"Loaded {len(boundaries)} boundary records.")
    print(f"Boundary coordinate system: {boundaries.crs}")

    return boundaries


