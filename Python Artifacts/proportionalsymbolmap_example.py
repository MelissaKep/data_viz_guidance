def get_historical_population():
    """
    Read the official Census Bureau historical population table.

    The table contains a state/region label followed by Resident Population
    and Percent Change rows. We retain only the Resident Population values
    for 1920 and 2020.
    """
    print_section("STEP 1 — RETRIEVING HISTORICAL CENSUS POPULATION DATA")
    print("Source: U.S. Census Bureau Historical Population Change Data")
    print("Retrieving the official 1920 and 2020 state population counts...")

    response = requests.get(
        DATA_PAGE_URL,
        timeout=120,
        headers={"User-Agent": "Mozilla/5.0 (compatible; CensusVisualizationExample/1.0)"}
    )
    response.raise_for_status()

    # pandas reads the HTML table directly from the downloaded page content.
    tables = pd.read_html(response.text, flavor="lxml")

    target_table = None
    for table in tables:
        table_as_text = table.astype(str).to_string()
        if "Alabama" in table_as_text and "Resident Population" in table_as_text:
            target_table = table.copy()
            break

    if target_table is None:
        raise ValueError(
            "Could not find the expected state population table on the "
            "Census Bureau webpage. The page layout may have changed."
        )

    # Flatten any multi-level column headers produced by read_html.
    if isinstance(target_table.columns, pd.MultiIndex):
        target_table.columns = [
            " ".join(normalize_text(part) for part in col if normalize_text(part))
            for col in target_table.columns
        ]
    else:
        target_table.columns = [normalize_text(col) for col in target_table.columns]

    # The page uses a two-row pattern for each geography:
    # geography name, then Resident Population / Percent Change.
    # We extract the row labelled Resident Population and identify the year
    # columns by looking for the 1920 and 2020 labels in the headers.
    columns = list(target_table.columns)

    def find_year_column(year):
        candidates = [
            col for col in columns
            if str(year) in col and "Census" in col
        ]
        if candidates:
            return candidates[0]

        # Some pandas versions flatten the headers differently.
        candidates = [col for col in columns if str(year) in col]
        if candidates:
            return candidates[0]

        raise KeyError(
            f"Could not identify the {year} column. Available columns: {columns}"
        )

    year_1920_col = find_year_column(YEAR_OLDER)
    year_2020_col = find_year_column(YEAR_NEWER)

    # Determine which column contains row labels such as state names and
    # "Resident Population".
    label_col = columns[0]

    rows = []
    current_geography = None

    for _, row in target_table.iterrows():
        label = normalize_text(row[label_col])

        if label in ("", "nan", "None"):
            continue

        if label == "Resident Population":
            if current_geography is not None:
                value_1920 = pd.to_numeric(row[year_1920_col], errors="coerce")
                value_2020 = pd.to_numeric(row[year_2020_col], errors="coerce")

                if pd.notna(value_1920) and pd.notna(value_2020):
                    rows.append({
                        "NAME": current_geography,
                        "POP_1920": int(value_1920),
                        "POP_2020": int(value_2020),
                    })
            continue

        if label == "Percent Change":
            continue

        # Exclude section headings and national/region totals. Valid state
        # names are checked later against the TIGER/Line boundary records.
        current_geography = label

    population = pd.DataFrame(rows)

    if population.empty:
        raise ValueError(
            "The Census population table was downloaded, but no population "
            "records could be extracted. Check the webpage table structure."
        )

    # Remove national totals, Census regions, Puerto Rico, and other entries.
    population["NAME"] = population["NAME"].str.replace(
        r"\s+", " ", regex=True
    ).str.strip()

    population = population.drop_duplicates(subset="NAME")

    print(f"Retrieved {len(population)} historical geography records.")
    print(population.head(8).to_string(index=False))

    return population


