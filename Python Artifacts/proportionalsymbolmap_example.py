def prepare_map_data(population, boundaries):
    """Join the historical counts to state boundaries and calculate change."""
    print_section("STEP 3 — JOINING AND VALIDATING THE DATA")

    # Exclude territories and island areas from the state map.
    # Keep the 50 states and District of Columbia.
    excluded_fips = {
        "60", "66", "69", "72", "78"  # U.S. territories
    }
    states = boundaries.loc[
        ~boundaries["STATEFP"].astype(str).str.zfill(2).isin(excluded_fips)
    ].copy()

    # Join by the Census geography name. Names in the historical table and
    # TIGER/Line NAME field use standard full state names.
    mapped = states.merge(
        population,
        how="left",
        on="NAME",
        validate="one_to_one"
    )

    missing = mapped.loc[mapped["POP_1920"].isna() | mapped["POP_2020"].isna(), "NAME"]
    if not missing.empty:
        raise ValueError(
            "Population values could not be matched for: "
            + ", ".join(missing.tolist())
        )

    mapped["POP_CHANGE"] = mapped["POP_2020"] - mapped["POP_1920"]
    mapped["PCT_CHANGE"] = (
        mapped["POP_CHANGE"] / mapped["POP_1920"] * 100
    )

    print(f"Successfully matched {len(mapped)} geographies.")
    print(
        f"2020 total across mapped geographies: "
        f"{mapped['POP_2020'].sum():,}"
    )
    print(
        f"1920 total across mapped geographies: "
        f"{mapped['POP_1920'].sum():,}"
    )

    return mapped


