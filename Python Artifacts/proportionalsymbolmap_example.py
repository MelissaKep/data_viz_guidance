def export_outputs(mapped, figure, interactive_figure):
    """Export high-resolution map files, data, and reproducibility notes."""
    print_section("STEP 5 — EXPORTING OUTPUT FILES")

    png_path = OUTPUT_FOLDER / "population_comparison_1920_2020.png"
    pdf_path = OUTPUT_FOLDER / "population_comparison_1920_2020.pdf"
    csv_path = OUTPUT_FOLDER / "population_comparison_1920_2020_data.csv"
    notes_path = OUTPUT_FOLDER / "run_notes.txt"
    html_path = OUTPUT_FOLDER / "population_comparison_1920_2020_interactive.html"

    export_columns = [
        "NAME", "STATEFP", "GEOID",
        "POP_1920", "POP_2020", "POP_CHANGE", "PCT_CHANGE"
    ]
    missing = [col for col in export_columns if col not in mapped.columns]
    if missing:
        raise KeyError(
            f"Required export columns are missing: {missing}. "
            f"Available columns: {list(mapped.columns)}"
        )

    figure.savefig(png_path, dpi=300, bbox_inches="tight", facecolor=figure.get_facecolor())
    figure.savefig(pdf_path, bbox_inches="tight", facecolor=figure.get_facecolor())
    interactive_figure.write_html(
        html_path,
        include_plotlyjs=True,
        full_html=True
    )

    export_data = mapped[export_columns].copy()
    export_data["PCT_CHANGE"] = export_data["PCT_CHANGE"].round(2)
    export_data.to_csv(csv_path, index=False)

    notes = f"""U.S. Census Proportional Symbol Map — 1920 vs. 2020

DATA STORY
How has the geographic distribution of the U.S. population changed over
the century from 1920 to 2020?

DATA SOURCES
Historical population counts:
{DATA_PAGE_URL}

Geographic boundaries:
{TIGER_URL}

METHOD
- Population values are decennial Census resident population counts.
- Marker AREA is scaled linearly to population.
- 1920 symbols are green; 2020 symbols are pink.
- Symbols are offset horizontally to make both years visible.
- State boundaries use 2020 TIGER/Line geography.
- Alaska and Hawaii are displayed in separate inset panels.

GEOGRAPHIC AND COMPARABILITY NOTE
Alaska and Hawaii were territories in 1920, not states. Their 1920 values
represent the populations of the territories that later became states.
The 2020 values represent state populations. Interpret those two comparisons
with this historical distinction in mind.

OUTPUTS
- {png_path.name}
- {pdf_path.name}
- {csv_path.name}

REPRODUCIBILITY
Run date: {pd.Timestamp.now().isoformat(timespec="seconds")}
Python: {sys.version.split()[0]}
"""
    notes_path.write_text(notes, encoding="utf-8")

    print("Export completed:")
    for path in (png_path, pdf_path, csv_path, html_path, notes_path):
        print(f"  {path}")


