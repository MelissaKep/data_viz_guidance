def create_interactive_map(mapped):
    """
    Create an interactive HTML version of the paired-circle map.

    Hovering over either year's symbol reveals the state name, exact population
    for both years, absolute change, and percentage change. Plotly's USA
    geographic projection includes Alaska and Hawaii in its U.S. layout.
    """
    print_section("STEP 4B — CREATING INTERACTIVE HOVER MAP")

    # Use representative points for reliable point placement inside each state.
    points = mapped.to_crs("EPSG:4326").copy()
    centers = points.geometry.representative_point()

    points["longitude"] = centers.x
    points["latitude"] = centers.y

    customdata = np.column_stack([
        points["NAME"].astype(str).to_numpy(),
        points["POP_1920"].astype("int64").to_numpy(),
        points["POP_2020"].astype("int64").to_numpy(),
        points["POP_CHANGE"].astype("int64").to_numpy(),
        points["PCT_CHANGE"].astype(float).to_numpy()
    ])

    max_population = float(points[["POP_1920", "POP_2020"]].to_numpy().max())
    desired_max_marker_diameter = 42

    # Plotly uses a sizeref calculation for area-based marker sizing.
    sizeref = 2.0 * max_population / (desired_max_marker_diameter ** 2)

    fig = go.Figure()

    # Pink outer circles: 2020 counts.
    fig.add_trace(go.Scattergeo(
        lon=points["longitude"],
        lat=points["latitude"],
        mode="markers",
        name="2020 Population",
        customdata=customdata,
        marker=dict(
            size=points["POP_2020"],
            sizemode="area",
            sizeref=sizeref,
            sizemin=4,
            color="#D96AAE",
            opacity=0.88,
            line=dict(color="#B84F91", width=1)
        ),
        hovertemplate=(
            "<b>%{customdata[0]}</b><br>"
            "2020 population: %{customdata[2]:,.0f}<br>"
            "1920 population: %{customdata[1]:,.0f}<br>"
            "Population change: %{customdata[3]:+,.0f}<br>"
            "Percentage change: %{customdata[4]:+.1f}%"
            "<extra>2020 Population</extra>"
        )
    ))

    # Green inner circles: 1920 counts.
    fig.add_trace(go.Scattergeo(
        lon=points["longitude"],
        lat=points["latitude"],
        mode="markers",
        name="1920 Population",
        customdata=customdata,
        marker=dict(
            size=points["POP_1920"],
            sizemode="area",
            sizeref=sizeref,
            sizemin=2,
            color="#35B89A",
            opacity=1.0,
            line=dict(color="#16866F", width=0.8)
        ),
        hovertemplate=(
            "<b>%{customdata[0]}</b><br>"
            "1920 population: %{customdata[1]:,.0f}<br>"
            "2020 population: %{customdata[2]:,.0f}<br>"
            "Population change: %{customdata[3]:+,.0f}<br>"
            "Percentage change: %{customdata[4]:+.1f}%"
            "<extra>1920 Population</extra>"
        )
    ))

    # Setup a vertically-stacked layout for the interactive legend circles
    # to mimic the static chart style rather than using nested shapes.
    # Using coordinates in 'paper' space
    legend_vals = [40, 20, 10, 5, 1]
    y_positions = [0.27, 0.22, 0.17, 0.12, 0.07]
    shapes = []
    annotations = [
        dict(
            text="Resident Population",
            x=0.84, y=0.32, xref="paper", yref="paper",
            showarrow=False, xanchor="center",
            font=dict(size=11, color="#202B32", weight="bold")
        )
    ]

    for y_pos, val in zip(y_positions, legend_vals):
        # Scale circle radius to mimic the static map's styling in paper coordinates
        r_x = 0.02 * np.sqrt(val / 40.0)
        r_y = r_x * 1.55 # Aspect ratio multiplier to keep shapes circular on the tall canvas

        shapes.append(dict(
            type="circle", xref="paper", yref="paper",
            x0=0.80 - r_x, x1=0.80 + r_x,
            y0=y_pos - r_y, y1=y_pos + r_y,
            line=dict(color="#202B32", width=1),
            fillcolor="rgba(82, 104, 117, 0.6)"
        ))

        annotations.append(dict(
            text=f"{val} Million",
            x=0.835, y=y_pos, xref="paper", yref="paper",
            showarrow=False, xanchor="left",
            font=dict(size=9, color="#202B32")
        ))

    # Add general footer annotations
    annotations.extend([
        dict(
            text=(
                "Hover over a circle to see exact population counts for "
                "both years, total change, and percentage change. "
                "Alaska and Hawaii were territories in 1920."
            ),
            x=0.5, y=-0.055, xref="paper", yref="paper",
            showarrow=False, xanchor="center",
            font=dict(size=10, color="#425762")
        ),
        dict(
            text=(
                "Source: U.S. Census Bureau, Historical Population Change "
                "Data (1910–2020); 2020 TIGER/Line boundaries."
            ),
            x=0.5, y=-0.085, xref="paper", yref="paper",
            showarrow=False, xanchor="center",
            font=dict(size=9, color="#526875")
        )
    ])

    fig.update_layout(
        title=dict(
            text="Population Growth From 1920 to 2020",
            x=0.5,
            xanchor="center",
            font=dict(size=23, color="#202B32")
        ),
        paper_bgcolor="#D8EFF9",
        plot_bgcolor="#D8EFF9",
        font=dict(family="Arial, sans-serif", color="#263640"),
        legend=dict(
            orientation="v",
            yanchor="top",
            y=0.88,
            xanchor="left",
            x=0.76,
            bgcolor="rgba(255,255,255,0.6)",
            borderwidth=1,
            bordercolor="#B8C4CB",
            font=dict(size=10)
        ),
        margin=dict(l=10, r=10, t=75, b=85),
        height=780,
        geo=dict(
            scope="usa",
            domain=dict(x=[0.015, 0.735], y=[0.025, 0.96]),
            projection_type="albers usa",
            showland=True,
            landcolor="#FFFFFF",
            showocean=True,
            oceancolor="#D8EFF9",
            showlakes=True,
            lakecolor="#D8EFF9",
            showcountries=False,
            showsubunits=True,
            subunitcolor="#B8C4CB",
            subunitwidth=0.7,
            showcoastlines=True,
            coastlinecolor="#B8C4CB",
            bgcolor="#D8EFF9"
        ),
        shapes=shapes,
        annotations=annotations
    )

    return fig


